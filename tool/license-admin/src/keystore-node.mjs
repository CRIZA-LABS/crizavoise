// Local keystore: the Criza Labs signing keys in <repo>/.secrets (never
// committed). A hosted version would read the same JSON from Worker secrets.
import fs from 'node:fs';
import path from 'node:path';
import { importSigningKey, newKeyFile, unb64 } from './crypto.mjs';

const LICENCE = 'license_signing_key.json';
const RESET = 'reset_signing_key.json';

export function nodeKeystore({ secretsDir, repoDir }) {
  let cache = {};
  const read = (f) => {
    const p = path.join(secretsDir, f);
    if (!fs.existsSync(p)) {
      throw new Error(`Signing key not found: ${p}. Run "dart run tool/license/generate.dart init" or restore your .secrets backup.`);
    }
    return JSON.parse(fs.readFileSync(p, 'utf8'));
  };

  const load = async (f) => (cache[f] ??= await importSigningKey(read(f)));

  function dartFile(lic, reset) {
    const rows = (b) => {
      const a = [...b], out = [];
      for (let i = 0; i < a.length; i += 16) out.push(`    ${a.slice(i, i + 16).join(', ')},`);
      return out.join('\n');
    };
    return `// Generated by tool/license/generate.dart init. Public keys only: they can
// check signatures but never create them. The private keys stay with
// Criza Labs in .secrets/ (never committed, never shipped).
class CrizaKeys {
  CrizaKeys._();

  /// Verifies licence keys.
  static const List<int> licensePublicKey = [
${rows(lic)}
  ];

  /// Verifies admin password reset codes.
  static const List<int> resetPublicKey = [
${rows(reset)}
  ];
}
`;
  }

  return {
    licenceKey: () => load(LICENCE),
    resetKey: () => load(RESET),
    licencePublic: async () => unb64(read(LICENCE).public),
    info() {
      const lic = read(LICENCE), reset = read(RESET);
      return {
        secretsDir,
        licence: { created: lic.created, public: lic.public },
        reset: { created: reset.created, public: reset.public },
      };
    },
    /**
     * New key pairs. Old ones move to .secrets/retired-<timestamp>/ (kept, not
     * deleted) and lib/licensing/license_keys.dart is rewritten, so the next
     * app build accepts only keys signed with the new pair.
     */
    async rotate() {
      const stamp = new Date().toISOString().replace(/[:.]/g, '-');
      const retired = path.join(secretsDir, `retired-${stamp}`);
      fs.mkdirSync(retired, { recursive: true });
      for (const f of [LICENCE, RESET]) {
        const p = path.join(secretsDir, f);
        if (fs.existsSync(p)) fs.copyFileSync(p, path.join(retired, f));
      }
      const lic = await newKeyFile(), reset = await newKeyFile();
      fs.writeFileSync(path.join(secretsDir, LICENCE), JSON.stringify(lic, null, 2));
      fs.writeFileSync(path.join(secretsDir, RESET), JSON.stringify(reset, null, 2));
      const dart = path.join(repoDir, 'lib', 'licensing', 'license_keys.dart');
      fs.writeFileSync(dart, dartFile(unb64(lic.public), unb64(reset.public)));
      cache = {};
      return { retired, dart };
    },
  };
}

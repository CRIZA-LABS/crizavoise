// CrizaVoise licence and reset-code generator (Criza Labs only).
//
//   dart run tool/license/generate.dart init
//   dart run tool/license/generate.dart license --plan 1y --name "Shop" \
//       --email owner@shop.in --device 7KQ2-M9XD-4TPA-0WRC [--id CV-2026-0001]
//   dart run tool/license/generate.dart reset --installation <installation id>
//   dart run tool/license/generate.dart verify <licence key>
//
// Private keys live in .secrets/ (gitignored). Back that folder up offline:
// if it's lost, no new licences can be issued for existing app versions.
import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:cryptography/cryptography.dart';
import 'package:crizavoise/licensing/license_codec.dart';
import 'package:crizavoise/licensing/license_keys.dart';
import 'package:crizavoise/licensing/machine_id.dart';

const _secrets = '.secrets';
const _licenseKeyFile = '$_secrets/license_signing_key.json';
const _resetKeyFile = '$_secrets/reset_signing_key.json';
const _ledger = '$_secrets/issued_licenses.csv';
const _keysDart = 'lib/licensing/license_keys.dart';

Future<void> main(List<String> args) async {
  if (args.isEmpty) return _usage();
  final opts = _parse(args.skip(1).toList());
  switch (args.first) {
    case 'init':
      await _init(force: opts.containsKey('force'));
    case 'license':
      await _license(opts);
    case 'reset':
      await _reset(opts);
    case 'device':
      final id = await MachineId.read();
      if (id == null) _fail('could not read the machine ID of this computer');
      stdout.writeln(await DeviceCode.fromMachineId(id));
    case 'verify':
      await _verify(args.length > 1 ? args[1] : '');
    default:
      _usage();
  }
}

void _usage() {
  stdout.writeln('''
Commands:
  init                         create the signing keys (once)
  license --plan 6m|1y|life --name NAME --email EMAIL --device CODE [--id ID] [--issued YYYY-MM-DD]
  reset --installation ID      one-time admin password reset code (valid ~3 days)
  verify KEY                   show what a licence key contains
  device                       print THIS computer's device code (for testing)''');
  exitCode = 64;
}

Map<String, String> _parse(List<String> a) {
  final m = <String, String>{};
  for (var i = 0; i < a.length; i++) {
    if (!a[i].startsWith('--')) continue;
    final k = a[i].substring(2);
    final hasValue = i + 1 < a.length && !a[i + 1].startsWith('--');
    m[k] = hasValue ? a[++i] : 'true';
  }
  return m;
}

Never _fail(String msg) {
  stderr.writeln('Error: $msg');
  exit(1);
}

Future<SimpleKeyPair> _loadKey(String path) async {
  final f = File(path);
  if (!await f.exists()) _fail('$path not found. Run "init" first (or restore your .secrets backup).');
  final seed = base64.decode((jsonDecode(await f.readAsString()) as Map)['seed'] as String);
  return Ed25519().newKeyPairFromSeed(seed);
}

Future<List<int>> _newKey(String path) async {
  final rnd = Random.secure();
  final seed = List<int>.generate(32, (_) => rnd.nextInt(256));
  final pair = await Ed25519().newKeyPairFromSeed(seed);
  final pub = (await pair.extractPublicKey()).bytes;
  await File(path).writeAsString(const JsonEncoder.withIndent('  ').convert({
    'algorithm': 'Ed25519',
    'created': DateTime.now().toUtc().toIso8601String(),
    'seed': base64.encode(seed),
    'public': base64.encode(pub),
  }));
  return pub;
}

String _bytes(List<int> b) {
  final lines = <String>[];
  for (var i = 0; i < b.length; i += 16) {
    lines.add('    ${b.sublist(i, min(i + 16, b.length)).join(', ')},');
  }
  return lines.join('\n');
}

Future<void> _init({bool force = false}) async {
  if (!force && (File(_licenseKeyFile).existsSync() || File(_resetKeyFile).existsSync())) {
    _fail('Keys already exist in $_secrets/. Replacing them makes every issued '
        'licence invalid. Use --force only if you really mean it.');
  }
  await Directory(_secrets).create(recursive: true);
  final lic = await _newKey(_licenseKeyFile);
  final reset = await _newKey(_resetKeyFile);
  await File(_keysDart).writeAsString('''
// Generated by tool/license/generate.dart init. Public keys only: they can
// check signatures but never create them. The private keys stay with
// Criza Labs in .secrets/ (never committed, never shipped).
class CrizaKeys {
  CrizaKeys._();

  /// Verifies licence keys.
  static const List<int> licensePublicKey = [
${_bytes(lic)}
  ];

  /// Verifies admin password reset codes.
  static const List<int> resetPublicKey = [
${_bytes(reset)}
  ];
}
''');
  stdout.writeln('Created $_licenseKeyFile and $_resetKeyFile, and updated $_keysDart.');
  stdout.writeln('BACK UP the $_secrets folder offline now (e.g. two USB drives). Never share it.');
}

Future<void> _license(Map<String, String> o) async {
  final plan = LicensePlan.fromCode(o['plan']) ?? _fail('--plan must be 6m, 1y or life');
  final name = o['name'] ?? _fail('--name is required');
  final email = o['email'] ?? '';
  final device = o['device'] ?? _fail('--device is required (or "*" for any computer)');
  if (device != '*' && DeviceCode.normalize(device).length != 16) {
    _fail('device code should look like 7KQ2-M9XD-4TPA-0WRC');
  }
  final issued = o['issued'] != null
      ? DateTime.tryParse('${o['issued']}T00:00:00Z') ?? _fail('--issued must be YYYY-MM-DD')
      : DateTime.now().toUtc();
  final id = o['id'] ?? 'CV-${issued.year}-${DateTime.now().millisecondsSinceEpoch % 100000}';
  final payload = LicensePayload(
    id: id,
    name: name,
    email: email,
    plan: plan,
    issued: issued,
    expires: LicenseCodec.expiryFor(plan, issued),
    device: device == '*' ? '*' : device.toUpperCase(),
  );
  final pair = await _loadKey(_licenseKeyFile);
  final pub = (await pair.extractPublicKey()).bytes;
  if (!_same(pub, CrizaKeys.licensePublicKey)) {
    _fail('the key in $_licenseKeyFile does not match $_keysDart; this app build would reject it');
  }
  final key = await LicenseCodec.sign(payload, pair);
  final ledger = File(_ledger);
  if (!await ledger.exists()) {
    await ledger.writeAsString('issued_at,id,plan,name,email,device,expires\n');
  }
  String csv(String s) => '"${s.replaceAll('"', '""')}"';
  await ledger.writeAsString(
      '${DateTime.now().toUtc().toIso8601String()},${csv(id)},${plan.code},${csv(name)},'
      '${csv(email)},${payload.device},${payload.expires?.toIso8601String().substring(0, 10) ?? 'never'}\n',
      mode: FileMode.append);
  stdout.writeln('Licence ${payload.id} (${plan.code}) for $name, '
      'expires ${payload.expires?.toIso8601String().substring(0, 10) ?? 'never'}:\n');
  stdout.writeln(key);
}

Future<void> _reset(Map<String, String> o) async {
  final inst = o['installation'] ?? _fail('--installation is required');
  final pair = await _loadKey(_resetKeyFile);
  final bucket = DateTime.now().toUtc().millisecondsSinceEpoch ~/ Duration.millisecondsPerDay;
  final sig = await Ed25519().sign(utf8.encode('${inst.trim()}:$bucket'), keyPair: pair);
  stdout.writeln('Reset code (valid about 3 days, only on that installation):\n');
  stdout.writeln(base64.encode(sig.bytes));
}

Future<void> _verify(String key) async {
  final p = await LicenseCodec.verify(key, CrizaKeys.licensePublicKey);
  if (p == null) _fail('not a valid CrizaVoise licence key');
  stdout.writeln(const JsonEncoder.withIndent('  ').convert(p.toJson()));
}

bool _same(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return false;
  }
  return true;
}
